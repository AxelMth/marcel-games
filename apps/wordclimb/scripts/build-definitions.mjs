/**
 * Builds the definitions the "definition" hint shows, per locale, from the
 * vendored dictionaries — and refuses to emit one that gives the answer away.
 *
 * The app used to ship 40 hand-written definitions for a catalogue that needs
 * 1415, so almost every word fell back to a generic line. It also keyed them
 * as Record<word, {en, fr}>, which assumes a word exists in both languages: of
 * the 1415 words, 29 do. Hence one dictionary per locale, generated.
 *
 * What this script mostly does is refuse. A definition that spells out the
 * word it defines is not a hint, it is the solution — and the sources are full
 * of them, from "vise: Fait de viser" to a gloss that simply names the lemma.
 *
 * Run: pnpm --filter @marcel-games/wordclimb build:definitions
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const DATA_DIR = join(__dirname, "..", "lib", "data")
const SOURCE_DIR = join(__dirname, "..", "data-sources")
// The catalogue as build-catalogue.mjs mirrors it for the Go server: the same
// levels in the same order as lib/data/catalogue.ts, minus the TypeScript that
// a plain .mjs cannot import on the Node 20 the repo still allows.
const CATALOGUE_JSON = join(
  __dirname,
  "..",
  "..",
  "..",
  "server",
  "wordclimb",
  "internal",
  "constants",
  "catalogue.json"
)

const LOCALES = ["en", "fr"]
const MASK = "•••"

/**
 * Only the rungs. beginWord and endWord are printed on the ladder from the
 * first frame, so the player never types them and never needs them defined.
 */
function rungsOf(catalogue, locale) {
  const words = new Set()
  for (const level of catalogue[locale]) {
    for (const word of level.wordLadder) words.add(word.toLowerCase())
  }
  return [...words].sort()
}

/**
 * Whole-word occurrences of the answer, blanked. What this catches is the
 * senses phrased on the word's own root — "Action de traquer" for "traque" —
 * where no other sense exists to prefer. Incidental substrings are left alone:
 * "cocaïne" does not spell out "coca" to a player mid-guess.
 */
function maskWord(text, word) {
  return text.replace(new RegExp(`\\b${word}\\b`, "gi"), MASK)
}

function load(locale) {
  const entries = JSON.parse(
    readFileSync(join(SOURCE_DIR, `${locale}-definitions.json`), "utf-8")
  )
  return new Map(entries.map(({ word, definition }) => [word.toLowerCase(), definition]))
}

function definitionsFor(locale, words, dictionary) {
  const found = {}
  const missing = []

  for (const word of words) {
    const raw = dictionary.get(word)?.trim()
    // A definition that is nothing but the masked word says nothing at all.
    const masked = raw ? maskWord(raw, word) : null
    if (!masked || masked.replaceAll(MASK, "").trim().length < 3) {
      missing.push(word)
      continue
    }
    found[word] = masked
  }

  console.log(
    `${locale}: ${Object.keys(found).length}/${words.length} defined` +
      (missing.length
        ? ` (${missing.length} missing: ${missing.slice(0, 8).join(", ")}${missing.length > 8 ? ", …" : ""})`
        : "")
  )
  return found
}

const catalogue = JSON.parse(readFileSync(CATALOGUE_JSON, "utf-8"))
const byLocale = {}
for (const locale of LOCALES) {
  byLocale[locale] = definitionsFor(
    locale,
    rungsOf(catalogue, locale),
    load(locale)
  )
  if (Object.keys(byLocale[locale]).length === 0) {
    throw new Error(`Refusing to emit an empty dictionary for ${locale}`)
  }
}

const banner = `// GENERATED by scripts/build-definitions.mjs — do not edit by hand.
// One dictionary per locale: the two catalogues are all but disjoint word
// sets, sharing 29 words out of 1415, so a shared key would be a lie.
// Definitions come from Wiktionary and Wiktionnaire (CC BY-SA); see the
// credits section of the legal modal. Occurrences of the word inside its own
// definition are masked with ${MASK} — this text is a hint, not the answer.
`

const body = `${banner}
export const DEFINITIONS: Record<"en" | "fr", Record<string, string>> = {
  en: ${JSON.stringify(byLocale.en, null, 2)},
  fr: ${JSON.stringify(byLocale.fr, null, 2)},
}

export function getDefinition(word: string, lang: "en" | "fr"): string {
  const def = DEFINITIONS[lang][word.toLowerCase()]
  if (!def) return lang === "en" ? "Find the next word in the ladder!" : "Trouve le prochain mot de l'echelle !"
  return def
}
`

writeFileSync(join(DATA_DIR, "definitions.ts"), body)
console.log(
  `\nWrote lib/data/definitions.ts — ` +
    LOCALES.map((l) => `${l}: ${Object.keys(byLocale[l]).length}`).join(", ")
)
