export function getCountriesByContinent(continent: Continent): Country[] {
  return countries.filter((c) => c.continent === continent)
}

const countriesByCode = new Map(countries.map((c) => [c.code, c]))

export function getCountriesByCodes(codes: string[]): Country[] {
  return codes
    .map((code) => countriesByCode.get(code))
    .filter((c): c is Country => c != null)
}
