/**
 * Turns the country outlines into SVG paths the app can draw as they are.
 *
 * The app only ever colours countries in and frames one of them; it never asks
 * the map what is under a finger. That needs no map engine, so the outlines are
 * projected once, here, and shipped as plain path strings: no token, no network,
 * and nothing to parse at launch.
 *
 *   node scripts/build-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(here, "..", "..", "earthunt", "public", "data", "world.geo.json")
const OUTPUT = join(here, "..", "src", "map", "shapes.ts")

const WIDTH = 1000
// Web Mercator stretches without limit towards the poles. Stopping short of
// them keeps Antarctica a strip rather than half the map.
const NORTH = 84
const SOUTH = -60

const mercatorY = (latitude) => {
  const phi = (Math.max(SOUTH, Math.min(NORTH, latitude)) * Math.PI) / 180
  return Math.log(Math.tan(Math.PI / 4 + phi / 2))
}
const TOP = mercatorY(NORTH)
const SCALE = WIDTH / (2 * Math.PI)
const HEIGHT = Math.round((TOP - mercatorY(SOUTH)) * SCALE)

const round = (value) => Math.round(value * 10) / 10
const project = ([longitude, latitude]) => [
  round(((longitude + 180) / 360) * WIDTH),
  round((TOP - mercatorY(latitude)) * SCALE),
]

const { features } = JSON.parse(readFileSync(SOURCE, "utf8"))

const shapes = features
  .map((feature) => {
    const polygons =
      feature.geometry.type === "Polygon"
        ? [feature.geometry.coordinates]
        : feature.geometry.coordinates
    let minX = Infinity
    let minY = Infinity
    let maxX = -Infinity
    let maxY = -Infinity
    const d = polygons
      .flatMap((rings) =>
        rings.map((ring) => {
          const points = ring.map(project)
          for (const [x, y] of points) {
            minX = Math.min(minX, x)
            minY = Math.min(minY, y)
            maxX = Math.max(maxX, x)
            maxY = Math.max(maxY, y)
          }
          return `M${points.map(([x, y]) => `${x} ${y}`).join("L")}Z`
        })
      )
      .join("")
    return { code: feature.properties.ADM0_A3, d, box: [minX, minY, maxX, maxY] }
  })
  .sort((a, b) => a.code.localeCompare(b.code))

const body = `// GENERATED by scripts/build-map.mjs — do not edit by hand.

export interface CountryShape {
  /** ISO 3166-1 alpha-3, as in the country list. */
  code: string
  /** SVG path in map units. */
  d: string
  /** Bounding box in map units: left, top, right, bottom. */
  box: readonly [number, number, number, number]
}

export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}

export const SHAPES: readonly CountryShape[] = ${JSON.stringify(shapes, null, 1)}
`

writeFileSync(OUTPUT, body)
console.log(`Wrote src/map/shapes.ts — ${shapes.length} shapes, ${WIDTH} × ${HEIGHT}`)
